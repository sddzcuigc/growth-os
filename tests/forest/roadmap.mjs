import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {addLibrarySkill,addLibraryProject} from '../../forest/roadmap.mjs';
import {mergeSnapshots} from '../../forest/sync-core.mjs';
const library=JSON.parse(await readFile(new URL('../../forest/skill-library.json',import.meta.url),'utf8'));
const child={name:'示例',trees:[],coins:0,xp:0};
const one=addLibrarySkill(child,library,'life-bag');
assert.equal(one.last,null);assert.ok(Number.isFinite(Date.parse(one.createdAt)));
assert.equal(addLibrarySkill(child,library,'life-bag'),one);
one.reviews=2;assert.equal(addLibrarySkill(child,library,'life-bag').reviews,2);
const project=addLibraryProject(child,library,'family-lunch');
assert.equal(addLibraryProject(child,library,'family-lunch'),project);
assert.equal(child.projects.length,1);
assert.equal(new Set(project.skillIds).size,project.skillIds.length);
assert.ok(project.skillIds.includes(one.id));
assert.equal(child.coins,0);assert.equal(child.xp,0);
assert.equal(child.trees.flatMap(t=>t.skills).filter(s=>s.libraryId==='life-bag').length,1);
const existing={trees:[{id:'prior',name:'自定义',skills:[{id:'prior-skill',name:one.name,reviews:9}]}]};
assert.equal(addLibrarySkill(existing,library,'life-bag').id,'prior-skill');
assert.equal(existing.trees[0].skills[0].reviews,9);
const base={children:{hu:child}},left=structuredClone(base),right=structuredClone(base);
left.children.hu.projects[0].attempts.push({id:'left',result:'独立核账'});
right.children.hu.projects[0].attempts.push({id:'right',result:'成人示范后炒蛋'});
const merged=mergeSnapshots(base,left,right);
assert.deepEqual(merged.conflicts,[]);
assert.equal(merged.state.children.hu.projects[0].attempts.length,2);
assert.throws(()=>addLibrarySkill(child,library,'does-not-exist'));
for(const sk of library.skills){assert.ok(sk.steps.length>=5);assert.ok(sk.criteria.length);for(const ref of sk.sourceIds)assert.ok(library.sources[ref])}
console.log('Roadmap PASS: stable skill references, no duplicate imports, original history preserved, project attempts merge, planning gives no rewards');

