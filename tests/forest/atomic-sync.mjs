import assert from 'node:assert/strict';
import {openDatabase} from '../../forest-server/database.mjs';
import {createStore} from '../../forest-server/store.mjs';
const db=openDatabase({file:':memory:'}),store=createStore(db);
const user={uid:'atomic-parent',email:'atomic@example.com',emailVerified:true};
const state={version:23,current:'anan',categories:[{id:'life',name:'生活类'}],children:{anan:{name:'测试孩子',age:8,xp:0,coins:0,gems:0,trees:[{id:'life',name:'生活类',height:90,skills:[{id:'bag',name:'系塑料袋',reviews:0,minutes:0,difficulty:3,last:'2026-01-01T00:00:00Z'}]}],projects:[{id:'lunch',name:'为家人准备午餐',skillIds:['bag']}],reviewsHistory:[]}}};
store.create(user,state);
assert.equal(store.save(user,state,0).conflict,true,'unversioned overwrites must be rejected');
const task=store.dailyTasks(user,'anan','2026-10-20').tasks[0];
const submission=store.submitPractice(user,{taskId:task.id,clientEventId:'atomic-practice-0001',minutes:10});
const submissionId=submission.submission?.id||submission.id;
assert.ok(submissionId);
db.exec("CREATE TRIGGER fail_reward BEFORE INSERT ON family_skill_tree_reward_ledger BEGIN SELECT RAISE(ABORT,'injected ledger failure'); END;");
assert.throws(()=>store.reviewPractice(user,{submissionId,decision:'approve'}),/injected ledger failure/);
assert.equal(store.get(user).version,1);
assert.equal(store.get(user).state.children.anan.coins,0);
assert.equal(store.pendingApprovals(user).items.length,1);
assert.equal(store.listReviewEvents(user).length,0);
assert.equal(store.rewardLedger(user).entries.length,0);
db.exec('DROP TRIGGER fail_reward');
store.reviewPractice(user,{submissionId,decision:'approve'});
store.reviewPractice(user,{submissionId,decision:'approve'});
assert.equal(store.get(user).state.children.anan.trees[0].skills[0].reviews,1);
assert.equal(store.rewardLedger(user).entries.length,1);
assert.equal(store.get(user).state.children.anan.projects[0].skillIds[0],'bag');
assert.equal(store.snapshot(user,'anan','2026-10-20').protocol,23);
console.log('V23_ATOMIC_SYNC_PASS: version guard, transaction rollback, retry once, project/skill references preserved');
